CREATE TABLE settings (
    id                BIGINT PRIMARY KEY,
    resume_text       TEXT         NOT NULL,
    directions        TEXT         NOT NULL,
    countries         TEXT         NOT NULL,
    keywords          TEXT         NOT NULL,
    stop_words        TEXT         NOT NULL,
    min_score         INT          NOT NULL,
    digest_hour       INT          NOT NULL,
    remote_only       BOOLEAN      NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE vacancies (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source            VARCHAR(30)  NOT NULL,
    external_id       VARCHAR(200) NOT NULL,
    url               VARCHAR(1000) NOT NULL,
    title             VARCHAR(300) NOT NULL,
    company           VARCHAR(200) NOT NULL,
    country           VARCHAR(2),
    city              VARCHAR(120),
    work_mode         VARCHAR(10)  NOT NULL,
    language          VARCHAR(2)   NOT NULL,
    salary_min        INT,
    salary_max        INT,
    salary_currency   VARCHAR(3),
    description       TEXT         NOT NULL,
    skills            VARCHAR(1000) NOT NULL,
    direction         VARCHAR(100),
    published_at      TIMESTAMP WITH TIME ZONE,
    fetched_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    fingerprint       VARCHAR(64)  NOT NULL,
    prefilter_passed  BOOLEAN      NOT NULL,
    prefilter_reason  VARCHAR(300),
    match_score       INT,
    match_summary     VARCHAR(1000),
    match_strengths   TEXT,
    match_gaps        TEXT,
    match_advice      TEXT,
    scored_by         VARCHAR(10),
    scored_at         TIMESTAMP WITH TIME ZONE,
    hidden            BOOLEAN      NOT NULL DEFAULT FALSE,
    notified          BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_vacancy_source_external UNIQUE (source, external_id)
);
CREATE INDEX ix_vacancies_fingerprint ON vacancies (fingerprint);
CREATE INDEX ix_vacancies_fetched_at ON vacancies (fetched_at);
CREATE INDEX ix_vacancies_score ON vacancies (match_score);

CREATE TABLE applications (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vacancy_id        BIGINT       NOT NULL REFERENCES vacancies (id),
    status            VARCHAR(15)  NOT NULL,
    notes             TEXT,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    applied_at        TIMESTAMP WITH TIME ZONE,
    status_changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_application_vacancy UNIQUE (vacancy_id)
);

CREATE TABLE prompt_templates (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              VARCHAR(50)  NOT NULL UNIQUE,
    title             VARCHAR(200) NOT NULL,
    body              TEXT         NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE cover_letters (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vacancy_id        BIGINT       NOT NULL REFERENCES vacancies (id),
    language          VARCHAR(2)   NOT NULL,
    version           INT          NOT NULL,
    body              TEXT         NOT NULL,
    generated_by      VARCHAR(10)  NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_cover_letters_vacancy ON cover_letters (vacancy_id);

CREATE TABLE pipeline_runs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at       TIMESTAMP WITH TIME ZONE,
    trigger_type      VARCHAR(10)  NOT NULL,
    status            VARCHAR(10)  NOT NULL,
    fetched           INT          NOT NULL DEFAULT 0,
    new_vacancies     INT          NOT NULL DEFAULT 0,
    duplicates        INT          NOT NULL DEFAULT 0,
    passed_prefilter  INT          NOT NULL DEFAULT 0,
    scored            INT          NOT NULL DEFAULT 0,
    top_matches       INT          NOT NULL DEFAULT 0,
    log               TEXT
);

CREATE TABLE ai_usage (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    purpose           VARCHAR(20)  NOT NULL,
    model             VARCHAR(40)  NOT NULL,
    input_tokens      INT          NOT NULL,
    output_tokens     INT          NOT NULL,
    cache_read_tokens INT          NOT NULL,
    cache_write_tokens INT         NOT NULL,
    cost_usd          NUMERIC(12, 6) NOT NULL
);
CREATE INDEX ix_ai_usage_created ON ai_usage (created_at);
